/**
 * SVGR index template — builds `generated/index.ts` with named `XxxIcon` exports.
 */
const path = require("node:path")

module.exports = function indexTemplate(filePaths) {
  const lines = filePaths
    .map((file) => {
      const filePath = typeof file === "string" ? file : file.path
      const base = path.basename(filePath, path.extname(filePath))
      return `export { default as ${base.replace(/^Svg/, "")}Icon } from "./${base}"`
    })
    .sort()
  return `/* Auto-generated by \`npm run icons\`. Do not edit by hand. */\n${lines.join("\n")}\n`
}
